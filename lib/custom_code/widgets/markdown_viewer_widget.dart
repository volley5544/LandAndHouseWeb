\` \`4.4.6 \*\*ผู้กู้ หรือผู้ค้ำประกัน(ถ้ามี) ไม่ปฏิบัติตาม ข้อตกลง หรือเงื่อนไขใดๆ ในสัญญาฉบับนี้ ในกรณีที่ มีเหตุผิดนัด หรือผิดข้อตกลง ข้อใดข้อหนึ่งดังกล่าวข้างต้น ผู้ให้กู้ มีสิทธิบอกเลิกสัญญา และกำหนดให้ ต้นเงินกู้ ดอกเบี้ยในต้นเงินกู้ ค่าธรรมเนียม รวมถึงหากแต่ไม่จำกัดอยู่เพียง จำนวนเงินอื่นใด ที่ผู้กู้ ต้องชำระให้แก่ ผู้ให้กู้ ภายใต้สัญญาฉบับนี้ และเอกสารอื่นใด เป็นอันถึงกำหนดชำระทั้งจำนวน โดยที่ ผู้ให้กู้ จักทำการแจ้งให้ผู้กู้ ทราบล่วงหน้า อย่างน้อย 7 วัน ถึงการบอกเลิกสัญญาดังกล่าว และผู้กู้ จักยอมรับผิด และทำการชดใช้ค่าเสียหาย รวมถึงหากแต่ไม่จำกัดอยู่เพียง ค่าใช้จ่ายอื่นใด ให้แก่ ผู้ให้กู้ โดยทันที และทั้งจำนวน สำหรับ บรรดาความเสียหาย รวมถึงหากแต่ไม่จำกัดอยู่เพียง ค่าใช้จ่ายต่างๆ ที่ผู้ให้กู้ พึงเรียกได้ ตามกฎหมาย หรือตามสัญญาฉบับนี้ เป็นอีกส่วนหนึ่งได้ต่างหากด้วย ผู้กู้ ตกลง และรับทราบว่า ผู้ให้กู้ จะนำเงินที่ได้รับจากผู้กู้ ตามข้อสัญญานี้ ไปชำระ บรรดาหนี้อุปกรณ์ ที่ผู้กู้ มีต่อผู้ให้กู้ ตามสัญญา อันได้แก่ ค่าธรรมเนียมจัดการ ดอกเบี้ยค้างชำระ และค่าใช้จ่ายอื่นใดก่อน และหากยังมีเงินคงเหลืออยู่ ผู้ให้กู้ จะนำไป ชำระคืนหนี้ประธาน อันได้แก่ ต้นเงินกู้\*\*

\` \`5.\*\*เมื่อมีเหตุผิดนัด หรือผิดสัญญา ผู้ให้กู้ มีสิทธิแจ้งให้ ผู้กู้ ส่งมอบ และบังคับทรัพย์ที่เป็นประกัน ออกขาย หรือดำเนินการอื่นใด เพื่อนำเงินมาชำระหนี้ที่คงค้างชำระ ในทุกประเภท ของ ผู้กู้ ที่มีอยู่กับ ผู้ให้กู้ จนครบถ้วน หากในการบังคับทรัพย์ที่เป็นประกัน เพื่อการชำระหนี้ จนครบถ้วน แล้วนั้น ยังคงมีเงินเหลืออยู่ ผู้ให้กู้ จะส่งมอบคืนแก่ ผู้กู้\*\*

\` \`6.ในกรณีที่ ผู้กู้เปลี่ยนแปลงที่อยู่ และ/หรือ สถานที่ทำงาน และ/หรือ บัญชีเงินฝาก ที่ใช้หักเงินเพื่อชำระหนี้ในแต่ละงวด ผู้กู้ จะต้องแจ้งให้ ผู้ให้กู้ทราบ อย่างเป็นลายลักษณ์อักษร \*\*ภายใน 5 วัน\*\* นับตั้งแต่ วันที่มีการเปลี่ยนแปลงดังกล่าว และให้ถือว่า การบอกกล่าวเปลี่ยนแปลง \*\*ถือเป็นสาระสำคัญ\*\* ของสัญญาฉบับนี้ และผู้กู้ ตกลง และยินยอม อย่างที่ไม่มีเงื่อนไขใดๆ ให้ ผู้ให้กู้ สามารถทำการติดต่อ บอกกล่าว รวมถึงหากแต่ไม่จำกัดอยู่เพียง ทวงถาม ผ่านทางโทรศัพท์ หรือการส่งข้อความ บอกกล่าวทวงถาม ผ่านทางโทรศัพท์ได้ด้วย ตามหมายเลขโทรศัพท์ ที่ระบุไว้ใน ใบคำขอสินเชื่อ ที่ผู้กู้ ได้ให้ไว้ กับ ผู้ให้กู้ และ ผู้กู้ รับทราบ และตกลงว่า ในกรณีที่ ผู้กู้ ได้มีการเปลี่ยนแปลงหมายเลขโทรศัพท์ ผู้กู้ จะต้องแจ้งให้ผู้ให้กู้ ทราบ อย่างเป็นลายลักษณ์อักษร \*\*ภายใน 7 วัน\*\* นับจาก วันที่มีการเปลี่ยนแปลงดังว่านั้น หาก ผู้กู้ ไม่แจ้งให้ ผู้ให้กู้ทราบ ให้ถือว่า การโทรศัพท์ หรือการส่งข้อความ บอกกล่าวทวงถาม ผ่านทางโทรศัพท์ ที่ผู้ให้กู้ ได้ส่งไปตาม เจตนารมณ์ ของ ผู้กู้ มีผลสมบูรณ์แล้ว หากมีความเสียหายใดๆ เกิดขึ้น ผู้กู้ จักเป็น ผู้รับผิดชอบเองทั้งสิ้น และแต่เพียงผู้เดียว อีกทั้ง หาก ผู้กู้ มิได้มีการแจ้งถึง การเปลี่ยนแปลงที่อยู่ใหม่ ให้ถือเอา ที่อยู่ ที่ได้ระบุไว้ใน ใบคำขอสินเชื่อ เป็นสถานที่ติดต่อ ในการส่งคำบอกกล่าวต่อกันโดยชอบ หากการติดต่อ หรือการบอกกล่าว ได้ส่งไป โดยทางไปรษณีย์ลงทะเบียนตอบรับแล้ว หากแต่ ส่งให้ไม่ได้ ไม่ว่าด้วยเหตุใดก็ตาม ให้ถือว่า ได้มีการส่งคำบอกกล่าว หรือการติดต่อกันนั้น โดยชอบแล้ว โดยที่ มิต้องคำนึงถึงว่า จะมีผู้ใดรับไว้ หรือไม่ก็ตาม

\` \`7.ผู้กู้ ยังคงมีสิทธิ ในการครอบครอง และใช้ประโยชน์ ในทรัพย์ที่เป็นประกัน ได้โดยตลอดระยะเวลา หากไม่มีการผิดนัด หรือผิดสัญญาใดๆ และผู้กู้ จักต้องทำการดูแล และใช้สอย ทรัพย์ที่เป็นประกันนั้น อย่างดี ตามที่ปุถุชนทั่วไปพึงกระทำ ผู้กู้ จักต้องจัดให้มีการประกันวินาศภัย โดยให้ ผู้ให้กู้ เป็นผู้รับประโยชน์ รวมถึงหากแต่ไม่จำกัดอยู่เพียง ผู้กู้ หรือบุคคลอื่นใด จักไม่ใช้ หรือนำไปแสวงหาประโยชน์ ในทางที่ผิดกฎหมาย จักไม่นำทรัพย์ที่เป็นประกัน ไปก่อให้เกิดภาระผูกพันเพิ่มขึ้น โดยที่ ผู้กู้ จักยินยอมให้ ผู้ให้กู้ และ/หรือ ตัวแทนของผู้ให้กู้ เข้าตรวจดู ทรัพย์ที่เป็นประกันได้ เมื่อได้รับการแจ้งจากผู้ให้กู้แล้ว และ\*\*หาก ผู้กู้ ผิดนัด หรือผิดสัญญาใดๆ และได้รับแจ้งจาก ผู้ให้กู้ เพื่อบังคับทรัพย์ที่เป็นประกันได้โดยทันที จากการดังกล่าว ผู้กู้จักหยุดการครอบครอง ใช้ หรือแสวงหาประโยชน์ทั้งหลาย จาก ทรัพย์ที่เป็นประกันนั้น และผู้กู้ พร้อมที่จะสละซึ่งเจตนาในการครอบครอง และยินยอม อย่างที่ไม่มีเงื่อนไขใดๆ ในการส่งมอบทรัพย์ที่เป็นประกันนั้น โดยปราศจากการขัดขืน เมื่อมีการดำเนินการบังคับทรัพย์ที่เป็นประกัน เพื่อให้ ผู้ให้กู้ นำออกขาย หรือดำเนินการอื่นใด เพื่อบังคับชำระหนี้ ที่ผู้กู้ ค้างอยู่ จนครบถ้วน\*\*

\` \`8.ผู้กู้ ตกลงรับผิดชอบในค่าใช้จ่ายทั้งหลาย จากการติดตามทวงถามหนี้ ฟ้องร้องบังคับคดี (รวมทั้งค่าทนายความ) ในหนี้ที่ค้างชำระทั้งหลาย ตามสัญญาฉบับนี้ อีกทั้ง ค่าอากรแสตมป์ ภาษีอากรอื่นใดซึ่ง รวมถึงหากแต่ไม่จำกัดอยู่เพียง ภาษีธุรกิจเฉพาะ และ/หรือ ภาษีมูลค่าเพิ่ม และ การอื่นใด ที่ ผู้ให้กู้ สามารถเรียกเก็บได้ ตามกฎหมาย

\` \`9.ผู้ให้กู้ อาจจะทำการสละสิทธิ ที่จะบังคับให้ผู้กู้ ปฏิบัติตามข้อกำหนด และเงื่อนไข ข้อใดข้อหนึ่ง หรือหลายข้อ ของสัญญาฉบับนี้ ผู้กู้ตกลง และรับทราบว่า การสละสิทธิดังกล่าว จะไม่มีผลกระทบใดๆ ต่อสิทธิของผู้ให้กู้ ที่จะบังคับให้ผู้กู้ ปฏิบัติตามข้อกาหนด และเงื่อนไขในคราวต่อไป หรือในข้ออื่นๆ นั้น

\` \`10.ผู้ให้กู้ ขอสงวนสิทธิ แต่เพียงผู้เดียว ในการปรับปรุง เปลี่ยนแปลง เพิ่มเติม หรือแก้ไข ข้อกำหนด และเงื่อนไขต่างๆ ในเรื่องของ ดอกเบี้ย เบี้ยปรับ ค่าปรับ ตามสัญญาฉบับนี้ รวมทั้ง วิธีการชำระคืนเงินกู้ ดอกเบี้ย เบี้ยปรับ ค่าปรับ ค่าบริการ ค่าธรรมเนียม รวมถึงหากแต่ไม่จำกัดอยู่เพียง ค่าใช้จ่ายใดๆ ตามที่ผู้ให้กู้ จะเห็นสมควร โดยไม่ขัดต่อกฎหมายโดยที่ ผู้ให้กู้ จะแจ้งให้ผู้กู้ ทราบล่วงหน้า อย่างเป็นลายลักษณ์อักษร เป็นระยะเวลา ไม่น้อยกว่า สามสิบ (30) วัน หรือในกรณีเร่งด่วน ผู้ให้กู้ จะแจ้งทางจดหมาย หรือประกาศทางหนังสือพิมพ์ รายวันภาษาไทย ที่แพร่หลายในประเทศไทย ล่วงหน้า เป็นระยะเวลาไม่น้อยกว่า เจ็ด (7) วัน และแจ้งถึงการเปลี่ยนแปลงดังกล่าว อย่างเป็นลายลักษณ์อักษร ซ้ำอีกครั้งหนึ่งก็ได้

\` \`11.ผู้ให้กู้ และผู้กู้ ตกลงร่วมกันว่า ความไม่สมบูรณ์ หรือการตกเป็นโมฆะของสัญญาข้อใดข้อหนึ่ง หรือบางส่วน ย่อมไม่มีผลกระทบต่อ สัญญา ในข้ออื่นๆ หรือสัญญาที่เหลืออยู่ทั้งหมด โดยให้ สัญญาที่เหลืออยู่ตามที่ได้กล่าวมานั้น ยังคงมีผลใช้บังคับได้อยู่ต่อไป โดยสมบูรณ์

\` \`12.ผู้กู้ ไม่อาจทำการโอนสิทธิ และหน้าที่ทั้งหลายของตน ตามสัญญาฉบับนี้ ไปให้แก่บุคคลอื่นใด แต่ผู้ให้กู้ มีสิทธิ หรืออาจทำการโอนสิทธิ ของผู้ให้กู้ ตามสัญญาฉบับนี้ ไม่ว่าทั้งหมด หรือแต่บางส่วน ไปให้แก่บุคคลภายนอกได้เสมอ โดยผู้ให้กู้จะแจ้งเป็นลายลักษณ์อักษรแก่ผู้กู้ และให้ถือว่า สัญญาฉบับนี้ เป็นการแสดงถึง การให้ความยินยอม อย่างที่ไม่มีเงื่อนไขใดๆ ในการโอนสิทธิ โดยที่ มิต้องได้รับความยินยอมจากผู้กู้แต่อย่างใด และผู้กู้ ยินยอมให้ผู้ให้กู้ ทำการเปิดเผยข้อมูลทั้งหมด ตามสัญญาฉบับนี้ ไปให้แก่บุคคลผู้รับโอนสิทธิได้ โดยที่ จักไม่มีการโต้แย้งแต่อย่างใด แต่ผู้ให้กู้ จะแจ้งให้ผู้กู้ ทราบ อย่างเป็น ลายลักษณ์อักษร ถึงการโอนสิทธิดังกล่าว อย่างเป็นการล่วงหน้า ไม่น้อยกว่า 1 งวดการชำระหนี้ ทั้งนี้ การให้ความยินยอมของผู้กู้ จะมีอยู่เพียงเท่ากับ ระยะเวลาของสัญญาฉบับนี้

